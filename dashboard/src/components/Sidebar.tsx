import { NavLink, useNavigate } from "react-router-dom";
import { useAuth } from "../lib/auth";
import { useTenants } from "../lib/tenant-context";
import "./Sidebar.css";

const NAV_ITEMS = [
  { to: "/orders", label: "Orders", icon: OrdersIcon },
  { to: "/products", label: "Products", icon: ProductsIcon },
  { to: "/settings", label: "Settings", icon: SettingsIcon },
  { to: "/billing", label: "Billing", icon: BillingIcon },
];

export function Sidebar() {
  const { user, logout } = useAuth();
  const { tenants, activeTenant, setActiveTenantId } = useTenants();
  const navigate = useNavigate();

  const handleLogout = () => {
    logout();
    navigate("/login");
  };

  return (
    <aside className="sidebar">
      <div className="sidebar-brand">
        <span className="brand-led online" />
        KIOSK
      </div>

      {tenants.length > 0 && (
        <div className="tenant-switcher">
          <label htmlFor="tenant-select">Storefront</label>
          <select
            id="tenant-select"
            value={activeTenant?.id ?? ""}
            onChange={(e) => setActiveTenantId(e.target.value)}
          >
            {tenants.map((t) => (
              <option key={t.id} value={t.id}>
                {t.name}
              </option>
            ))}
          </select>
        </div>
      )}

      <nav className="sidebar-nav">
        {NAV_ITEMS.map((item) => (
          <NavLink
            key={item.to}
            to={item.to}
            className={({ isActive }) => `sidebar-link ${isActive ? "active" : ""}`}
          >
            <item.icon />
            {item.label}
          </NavLink>
        ))}
      </nav>

      <div className="sidebar-footer">
        <div className="sidebar-user mono">{user?.email}</div>
        <button className="sidebar-logout" onClick={handleLogout}>
          Sign out
        </button>
      </div>
    </aside>
  );
}

function OrdersIcon() {
  return (
    <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8">
      <path d="M9 11l3 3L22 4" />
      <path d="M21 12v7a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h11" />
    </svg>
  );
}

function ProductsIcon() {
  return (
    <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8">
      <rect x="3" y="3" width="18" height="18" rx="2" />
      <circle cx="8.5" cy="8.5" r="1.5" />
      <path d="m21 15-5-5L5 21" />
    </svg>
  );
}

